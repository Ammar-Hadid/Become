#!/bin/bash
set -Eeuo pipefail
psql -X -v ON_ERROR_STOP=1 --username postgres --dbname become <<'SQL'
\getenv owner_password BECOME_OWNER_PASSWORD
\getenv app_password BECOME_APP_PASSWORD
CREATE ROLE become_owner LOGIN PASSWORD :'owner_password'
  NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
CREATE ROLE become_app LOGIN PASSWORD :'app_password'
  NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
ALTER DATABASE become OWNER TO become_owner;
REVOKE ALL ON DATABASE become FROM PUBLIC;
GRANT CONNECT ON DATABASE become TO become_app;
ALTER SCHEMA public OWNER TO become_owner;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO become_app;
ALTER DEFAULT PRIVILEGES FOR ROLE become_owner IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO become_app;
ALTER DEFAULT PRIVILEGES FOR ROLE become_owner IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO become_app;
SQL
