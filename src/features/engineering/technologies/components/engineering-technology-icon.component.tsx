export function EngineeringTechnologyIcon({
  iconKey,
  className = "size-4",
}: {
  iconKey: string | null;
  className?: string;
}) {
  const icon =
    iconKey && Object.hasOwn(icons, iconKey) ? icons[iconKey] : undefined;
  if (!icon) return <Code2 className={className} aria-hidden="true" />;

  return (
    <svg
      viewBox="0 0 24 24"
      className={className}
      fill="currentColor"
      aria-hidden="true"
    >
      <path d={icon.path} />
    </svg>
  );
}
